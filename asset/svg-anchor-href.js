// SVG <a> elements (our diagram jump-links) expose `.href` as an
// SVGAnimatedString object, not a plain string like an HTML anchor. Quarto's
// own link-processing assumes every anchor's `.href` is a string:
// quarto-nav.js's index.html-stripping pass calls `.replace()` on it and
// throws the moment it reaches one of our diagram links, aborting the rest
// of that script for the whole page; the link-external-newwindow "is this
// internal" check runs a regex `.test()` against it, which silently
// stringifies to "[object SVGAnimatedString]", never matches, and so
// classifies every diagram link as external and forces it open in a new
// tab. Redefining the property to behave like a real anchor's — read the
// href attribute, resolve it against the document like a browser normally
// would — fixes what every script downstream of this one sees, instead of
// special-casing each affected script (one of which we don't control, since
// quarto-nav.js is regenerated by Quarto itself).
//
// Must load before quarto-nav.js and any other script that walks anchors,
// so this belongs in include-in-header, not include-after-body.
(function () {
  if (!window.SVGAElement) {
    return;
  }
  Object.defineProperty(SVGAElement.prototype, "href", {
    configurable: true,
    get: function () {
      var raw = this.getAttribute("href") || "";
      try {
        return new URL(raw, this.baseURI).href;
      } catch (e) {
        return raw;
      }
    },
    set: function (value) {
      this.setAttribute("href", value);
    },
  });
})();
